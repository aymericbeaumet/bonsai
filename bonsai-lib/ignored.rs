fn regenerable(name: &std::ffi::OsStr) -> bool {
    REGENERABLE.iter().any(|known| name == *known)
}

/// Paths `trim` never deletes. Like gitignore patterns, a glob without `/`
/// matches a file or directory name at any depth (`.env.*` keeps
/// `apps/web/.env.local`); one with `/` matches from the worktree root, and
/// `*` never crosses `/`. Everything below a kept directory is kept.
pub struct Keep {
    /// Built-in local state and `[add] copy`: outside regenerable directories.
    builtin: Globs,
    /// `[trim] keep`: everywhere.
    explicit: Globs,
}

#[derive(Default)]
struct Globs {
    anywhere: Vec<glob::Pattern>,
    anchored: Vec<glob::Pattern>,
}

impl Globs {
    fn new<'a>(patterns: impl IntoIterator<Item = &'a str>) -> Self {
        let mut globs = Self::default();
        for raw in patterns {
            let pattern = raw.trim_end_matches('/');
            let (list, pattern) = match pattern.strip_prefix('/') {
                Some(rooted) => (&mut globs.anchored, rooted),
                None if pattern.contains('/') => (&mut globs.anchored, pattern),
                None => (&mut globs.anywhere, pattern),
            };
            match glob::Pattern::new(pattern) {
                Ok(pattern) => list.push(pattern),
                Err(error) => eprintln!("bonsai: invalid keep glob '{raw}': {error}"),
            }
        }
        globs
    }

    fn matches(&self, rel: &Path) -> bool {
        let options = glob::MatchOptions {
            case_sensitive: true,
            require_literal_separator: true,
            require_literal_leading_dot: false,
        };
        rel.ancestors()
            .filter(|path| !path.as_os_str().is_empty())
            .any(|path| {
                let name = path
                    .file_name()
                    .map(|name| name.to_string_lossy())
                    .unwrap_or_default();
                let full = path.to_string_lossy().replace('\\', "/");
                self.anywhere
                    .iter()
                    .any(|pattern| pattern.matches_with(&name, options))
                    || self
                        .anchored
                        .iter()
                        .any(|pattern| pattern.matches_with(&full, options))
            })
    }
}

impl Keep {
    pub fn from_config(config: &Config) -> Self {
        Self {
            builtin: Globs::new(
                LOCAL_STATE
                    .iter()
                    .copied()
                    .chain(config.add.copy.iter().map(String::as_str)),
            ),
            explicit: Globs::new(config.trim.keep.iter().map(String::as_str)),
        }
    }

    /// Whether `rel` is kept; `regenerable` says it lies inside a
    /// dependency or build directory, where only explicit globs apply.
    pub fn protects(&self, rel: &Path, regenerable: bool) -> bool {
        self.explicit.matches(rel) || (!regenerable && self.builtin.matches(rel))
    }
}

/// Outermost ignored paths: wholly ignored directories are reported once,
/// without descending (git's `--directory`).
pub fn roots(worktree: &Path) -> Result<Vec<PathBuf>> {
    let output = Git::at(worktree).out_bytes(&[
        "ls-files",
        "-z",
        "--others",
        "--ignored",
        "--exclude-standard",
        "--directory",
    ])?;
    let paths = output
        .split(|byte| *byte == 0)
        .filter(|field| !field.is_empty())
        .map(path_from_git)
        .collect();
    Ok(outermost(paths))
}

/// What `trim` would delete from `worktree`, with disk usage. Protected
/// paths and nested repositories are kept; ignored directories holding them
/// are split so everything else inside still goes.
pub fn plan(worktree: &Path, keep: &Keep) -> Result<Plan> {
    let visits: Vec<(PathBuf, Visit)> = roots(worktree)?
        .into_par_iter()
        .map(|rel| {
            // A root listed file by file may already sit in `target/...`.
            let inside = rel
                .ancestors()
                .skip(1)
                .filter_map(Path::file_name)
                .any(regenerable);
            let visit = visit(worktree, &rel, keep, inside);
            (rel, visit)
        })
        .collect();
    let mut plan = collect(visits);
    plan.entries
        .sort_by(|a, b| b.bytes.cmp(&a.bytes).then_with(|| a.path.cmp(&b.path)));
    plan.kept.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(plan)
}

/// A visited path is either deletable as a whole (with its disk usage) or
/// partially kept, in which case its deletable parts are listed separately.
enum Visit {
    Whole { bytes: u64, items: u64 },
    Partial(Plan),
}

/// `inside` says a parent is a regenerable directory: everything below is
/// deleted whole unless an explicit `[trim] keep` glob says otherwise.
fn visit(root: &Path, rel: &Path, keep: &Keep, inside: bool) -> Visit {
    if keep.protects(rel, inside) {
        return kept(rel, KeepReason::Protected);
    }
    let full = root.join(rel);
    let meta = match fs::symlink_metadata(&full) {
        Ok(meta) => meta,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Visit::Whole { bytes: 0, items: 0 };
        }
        Err(_) => return Visit::Partial(Plan::default()), // unreadable: leave it
    };
    if !meta.is_dir() {
        return Visit::Whole {
            bytes: disk_usage(&meta),
            items: 1,
        };
    }
    if let Ok(git) = fs::symlink_metadata(full.join(".git")) {
        // Linked checkouts and submodules are independent work even inside
        // build output. Package-manager clones remain regenerable there.
        if !inside || !git.is_dir() {
            return kept(rel, KeepReason::Repository);
        }
    }
    let inside = inside || rel.file_name().is_some_and(regenerable);
    let Ok(children) = fs::read_dir(&full) else {
        return Visit::Partial(Plan::default()); // unreadable: leave it
    };
    let Ok(children) = children
        .map(|child| child.map(|child| rel.join(child.file_name())))
        .collect::<io::Result<Vec<_>>>()
    else {
        return Visit::Partial(Plan::default()); // incomplete inventory: leave it
    };
    let visits: Vec<(PathBuf, Visit)> = children
        .into_par_iter()
        .map(|child| {
            let visit = visit(root, &child, keep, inside);
            (child, visit)
        })
        .collect();
    if visits
        .iter()
        .all(|(_, visit)| matches!(visit, Visit::Whole { .. }))
    {
        let (bytes, items) = visits.iter().fold(
            (disk_usage(&meta), 1),
            |(bytes, items), (_, visit)| match visit {
                Visit::Whole {
                    bytes: child_bytes,
                    items: child_items,
                } => (bytes + child_bytes, items + child_items),
                Visit::Partial(_) => unreachable!(),
            },
        );
        Visit::Whole { bytes, items }
    } else {
        Visit::Partial(collect(visits))
    }
}

fn kept(rel: &Path, reason: KeepReason) -> Visit {
    Visit::Partial(Plan {
        entries: Vec::new(),
        kept: vec![Kept {
            path: rel.to_path_buf(),
            reason,
        }],
    })
}

fn collect(visits: Vec<(PathBuf, Visit)>) -> Plan {
    let mut plan = Plan::default();
    for (path, visit) in visits {
        match visit {
            Visit::Whole { bytes, items } => plan.entries.push(Entry { path, bytes, items }),
            Visit::Partial(partial) => plan.merge(partial),
        }
    }
    plan
}

/// Keep only paths without a listed ancestor (git may list both `dir/` and
/// `dir/file`), sorted.
fn outermost(mut paths: Vec<PathBuf>) -> Vec<PathBuf> {
    let set: std::collections::HashSet<PathBuf> = paths.iter().cloned().collect();
    paths.retain(|path| {
        !path
            .ancestors()
            .skip(1)
            .any(|ancestor| !ancestor.as_os_str().is_empty() && set.contains(ancestor))
    });
    paths.sort();
    paths.dedup();
    paths
}

fn path_from_git(field: &[u8]) -> PathBuf {
    let field = field.strip_suffix(b"/").unwrap_or(field);
    #[cfg(unix)]
    {
        use std::os::unix::ffi::OsStrExt;
        PathBuf::from(std::ffi::OsStr::from_bytes(field))
    }
    #[cfg(not(unix))]
    {
        PathBuf::from(String::from_utf8_lossy(field).into_owned())
    }
}

/// Allocated size, like `du` (sparse files and filesystem blocks count as
/// they do on disk); the apparent length where blocks are unavailable.
fn disk_usage(meta: &fs::Metadata) -> u64 {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        meta.blocks() * 512
    }
    #[cfg(not(unix))]
    {
        meta.len()
    }
}

/// Fan out only the first directory levels; files are unlinked in batches
/// without rayon scheduling or a metadata lookup per file. The caller's
/// rayon pool bounds concurrency across roots and their descendants.
const FAN_OUT_DEPTH: usize = 3;

/// Share the deletion limit across independent roots and their descendants.
/// More APFS unlink workers contend with each other; four won the disposable
/// package-tree benchmark over one, two, and the default worker count.
pub(crate) fn with_deletion_pool<T: Send>(work: impl FnOnce() -> T + Send) -> T {
    #[cfg(target_os = "macos")]
    {
        static POOL: std::sync::LazyLock<rayon::ThreadPool> = std::sync::LazyLock::new(|| {
            rayon::ThreadPoolBuilder::new()
                .num_threads(4)
                .build()
                .expect("cannot start deletion workers")
        });
        POOL.install(work)
    }
    #[cfg(not(target_os = "macos"))]
    {
        work()
    }
}

/// Remove a tree. Symlinks are removed, never followed, and
/// a path that is already gone counts as removed.
pub fn remove_tree(path: &Path) -> io::Result<()> {
    with_deletion_pool(|| remove_tree_with_progress(path, &AtomicU64::new(0)))
}

/// Remove a tree, counting deleted files, links and directories as it goes.
/// Inherits the caller's rayon pool; bulk callers use `with_deletion_pool`.
/// The counter matches `Entry::items` when the tree has not changed since
/// planning. Entries already missing are harmless and do not advance it.
pub fn remove_tree_with_progress(path: &Path, removed: &AtomicU64) -> io::Result<()> {
    #[cfg(unix)]
    {
        unix_remove::tree(path, removed)
    }
    #[cfg(not(unix))]
    {
        remove_portable(path, removed, FAN_OUT_DEPTH)
    }
}

#[cfg(unix)]
mod unix_remove {
    use super::*;
    use rustix::fd::AsFd;
    use rustix::fs::{AtFlags, Dir, FileType, Mode, OFlags, openat, unlinkat};
    use rustix::io::Errno;
    use std::ffi::CStr;

    pub(super) fn tree(path: &Path, removed: &AtomicU64) -> io::Result<()> {
        use std::os::unix::ffi::OsStrExt;
        let name = path.file_name().ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidInput,
                "cannot remove a filesystem root",
            )
        })?;
        let name = std::ffi::CString::new(name.as_bytes())?;
        let parent = path
            .parent()
            .filter(|path| !path.as_os_str().is_empty())
            .unwrap_or(Path::new("."));
        let parent = match fs::File::open(parent) {
            Ok(parent) => parent,
            Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
            Err(error) => return Err(error),
        };
        at(&parent, &name, false, removed, FAN_OUT_DEPTH).map_err(Into::into)
    }

    fn at(
        parent: impl AsFd,
        name: &CStr,
        directory: bool,
        removed: &AtomicU64,
        depth: usize,
    ) -> rustix::io::Result<()> {
        if !directory {
            match unlinkat(&parent, name, AtFlags::empty()) {
                Ok(()) => {
                    removed.fetch_add(1, Ordering::Relaxed);
                    return Ok(());
                }
                Err(Errno::NOENT) => return Ok(()),
                // macOS returns EPERM for unlinking directories.
                Err(Errno::ISDIR | Errno::PERM) => {}
                Err(error) => return Err(error),
            }
        }
        let fd = match openat(
            &parent,
            name,
            OFlags::RDONLY | OFlags::DIRECTORY | OFlags::NOFOLLOW | OFlags::CLOEXEC,
            Mode::empty(),
        ) {
            Ok(fd) => fd,
            Err(Errno::NOENT) => return Ok(()),
            // A directory replaced by a symlink is unlinked itself.
            Err(Errno::NOTDIR | Errno::LOOP) => {
                return count(unlinkat(&parent, name, AtFlags::empty()), removed);
            }
            Err(error) => return Err(error),
        };
        let mut dir = Dir::new(fd)?;
        let mut directories = Vec::new();
        let mut first_error = None;
        let mut files = 0;
        while let Some(entry) = dir.next() {
            let entry = match entry {
                Ok(entry) => entry,
                Err(error) => {
                    first_error.get_or_insert(error);
                    continue;
                }
            };
            let name = entry.file_name();
            if name == c"." || name == c".." {
                continue;
            }
            if entry.file_type() == FileType::Directory {
                directories.push(name.to_owned());
            } else {
                match unlinkat(dir.fd()?, name, AtFlags::empty()) {
                    Ok(()) => {
                        files += 1;
                        if files == 128 {
                            removed.fetch_add(files, Ordering::Relaxed);
                            files = 0;
                        }
                    }
                    Err(Errno::NOENT) => {}
                    // Also handles filesystems with unknown entry types.
                    Err(Errno::ISDIR | Errno::PERM) => directories.push(name.to_owned()),
                    Err(error) => {
                        first_error.get_or_insert(error);
                    }
                }
            }
        }
        removed.fetch_add(files, Ordering::Relaxed);
        let fd = dir.fd()?;
        let results: Vec<_> = if depth > 0 {
            directories
                .par_iter()
                .map(|name| at(fd, name, true, removed, depth - 1))
                .collect()
        } else {
            directories
                .iter()
                .map(|name| at(fd, name, true, removed, 0))
                .collect()
        };
        for result in results {
            if let Err(error) = result {
                first_error.get_or_insert(error);
            }
        }
        if let Some(error) = first_error {
            return Err(error);
        }
        count(unlinkat(&parent, name, AtFlags::REMOVEDIR), removed)
    }

    fn count(result: rustix::io::Result<()>, removed: &AtomicU64) -> rustix::io::Result<()> {
        match result {
            Ok(()) => {
                removed.fetch_add(1, Ordering::Relaxed);
                Ok(())
            }
            Err(Errno::NOENT) => Ok(()),
            Err(error) => Err(error),
        }
    }
}

#[cfg(not(unix))]
fn remove_portable(path: &Path, removed: &AtomicU64, depth: usize) -> io::Result<()> {
    let result = (|| {
        let meta = fs::symlink_metadata(path)?;
        if meta.is_dir() {
            let children = fs::read_dir(path)?.collect::<io::Result<Vec<_>>>()?;
            let results: Vec<_> = if depth > 0 {
                children
                    .par_iter()
                    .map(|child| remove_portable(&child.path(), removed, depth - 1))
                    .collect()
            } else {
                children
                    .iter()
                    .map(|child| remove_portable(&child.path(), removed, 0))
                    .collect()
            };
            results.into_iter().collect::<io::Result<()>>()?;
            fs::remove_dir(path)
        } else {
            remove_entry(path, &meta)
        }
    })();
    match result {
        Ok(()) => {
            removed.fetch_add(1, Ordering::Relaxed);
            Ok(())
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error),
    }
}

/// Remove a file or a link (never its target).
#[cfg(not(unix))]
fn remove_entry(path: &Path, meta: &fs::Metadata) -> io::Result<()> {
    match fs::remove_file(path) {
        Err(_) if meta.file_type().is_symlink() => fs::remove_dir(path),
        #[cfg(windows)]
        Err(error) if error.kind() == io::ErrorKind::PermissionDenied => {
            make_writable(path, meta)?;
            fs::remove_file(path)
        }
        result => result,
    }
}

/// Windows refuses to delete read-only files (common in package caches).
#[cfg(windows)]
#[allow(clippy::permissions_set_readonly_false)]
fn make_writable(path: &Path, meta: &fs::Metadata) -> io::Result<()> {
    let mut permissions = meta.permissions();
    permissions.set_readonly(false);
    fs::set_permissions(path, permissions)
}

/// Delete the ignored paths of each checkout concurrently, right before
/// Git removes it: usually the bulk of a checkout, so Git is left with
/// little to do. Kept paths and nested repositories are left for Git's own
/// removal, so a worktree Git then refuses to remove keeps them. The same
/// plan as trim preserves protected descendants inside ignored directories.
pub fn purge(worktrees: &[(PathBuf, &Keep)]) {
    let work: Vec<PathBuf> = worktrees
        .par_iter()
        // Submodule checkouts stay for git's own removal checks.
        .filter(|(worktree, _)| !worktree.join(".gitmodules").exists())
        .flat_map_iter(|(worktree, keep)| {
            plan(worktree, keep)
                .unwrap_or_default()
                .entries
                .into_iter()
                .map(|entry| worktree.join(entry.path))
                .collect::<Vec<_>>()
        })
        .collect();
    work.par_iter().for_each(|path| {
        let _ = remove_tree(path); // best effort: git removes what remains
    });
}

/// Compact binary size: 512B, 12K, 3.4M, 1.2G.
pub fn format_bytes(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["B", "K", "M", "G", "T"];
    let mut value = bytes as f64;
    let mut unit = 0;
    while value >= 1024.0 && unit < UNITS.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    if unit == 0 {
        format!("{bytes}B")
    } else if value < 10.0 {
        format!("{value:.1}{}", UNITS[unit])
    } else {
        format!("{value:.0}{}", UNITS[unit])
    }
}

