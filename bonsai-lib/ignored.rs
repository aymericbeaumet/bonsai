//! Git-ignored content of a checkout (node_modules, target, .venv, ...):
//! what `trim` reclaims and what removal deletes concurrently before git
//! unregisters a worktree. Planning and supported deletion backends use rayon.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use anyhow::Result;
use rayon::prelude::*;
use serde::Serialize;

use crate::config::Config;
use crate::git::Git;

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Entry {
    /// Relative to the worktree.
    pub path: PathBuf,
    pub bytes: u64,
    /// Files, symlinks, and directories included in this entry.
    pub items: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum KeepReason {
    /// Matches `[add] copy` or `[trim] keep`: local config, not artifacts.
    Protected,
    /// A nested repository, which may hold unpushed work of its own.
    Repository,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Kept {
    pub path: PathBuf,
    pub reason: KeepReason,
}

/// Ignored paths to delete, outermost first, and the ignored paths kept.
#[derive(Debug, Default, Serialize)]
pub struct Plan {
    pub entries: Vec<Entry>,
    pub kept: Vec<Kept>,
}

impl Plan {
    pub fn bytes(&self) -> u64 {
        self.entries.iter().map(|entry| entry.bytes).sum()
    }

    fn merge(&mut self, other: Plan) {
        self.entries.extend(other.entries);
        self.kept.extend(other.kept);
    }
}

