    #[test]
    fn concurrent_removers_tolerate_entries_disappearing() {
        let tmp = tempfile::tempdir().unwrap();
        let tree = tmp.path().join("tree");
        for i in 0..32 {
            let dir = tree.join(i.to_string());
            fs::create_dir_all(&dir).unwrap();
            for j in 0..16 {
                fs::write(dir.join(j.to_string()), "x").unwrap();
            }
        }
        let first_count = AtomicU64::new(0);
        let second_count = AtomicU64::new(0);
        std::thread::scope(|scope| {
            let first = scope.spawn(|| remove_tree_with_progress(&tree, &first_count));
            let second = scope.spawn(|| remove_tree_with_progress(&tree, &second_count));
            first.join().unwrap().unwrap();
            second.join().unwrap().unwrap();
        });
        for counter in [&first_count, &second_count] {
            assert!(counter.load(Ordering::Relaxed) <= 1 + 32 * 17);
        }
        assert!(!tree.exists());
    }

